import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

// Writes an import per web build file so `bun build --compile` embeds the whole app in the binary.
// Without a web build it maps index.html to the placeholder page, so server tests never need one.
const root = join(import.meta.dir, '..')
const dist = join(root, 'apps/web/dist')
const out = join(root, 'apps/server/src/web-assets.gen.ts')

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    return statSync(path).isDirectory() ? walk(path) : [path]
  })
}

const entries: [string, string][] = existsSync(join(dist, 'index.html'))
  ? walk(dist).map((file) => [`/${relative(dist, file)}`, `../../web/dist/${relative(dist, file)}`])
  : [['/index.html', '../static/index.html']]

const lines = [
  '// @ts-nocheck: generated by scripts/gen-web-assets.ts; the imports are embedded files, not modules.',
  ...entries.map(([, from], i) => `import a${i} from '${from}' with { type: 'file' }`),
  '',
  'const path = (file: unknown) => file as string',
  '',
  'export const WEB_ASSETS: Record<string, string> = {',
  ...entries.map(([url], i) => `  '${url}': path(a${i}),`),
  '}',
  '',
]
writeFileSync(out, lines.join('\n'))
console.info(`web assets: ${entries.length} file(s)`)
